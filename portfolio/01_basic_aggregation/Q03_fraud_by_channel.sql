-- ============================================================
-- Q03. 채널별 Fraud 발생 건수
-- ============================================================
-- [비즈니스 문제]
--   모바일, 온라인, 오프라인 등 거래 채널 중 어떤 채널에서
--   사기 거래가 집중되는지 확인한다.
--   채널별 취약점을 파악하면 채널 특화 탐지 Rule을 설계할 수 있다.
--
-- [사용 기술]
--   - GROUP BY + FILTER 조건부 집계
--
-- [FDS Insight]
--   비대면 채널(모바일·온라인)에서 fraud 비중이 높다면
--   해당 채널의 인증 절차 강화 또는 추가 Rule 적용을 검토해야 한다.
-- ============================================================

SELECT
    channel,
    COUNT(*) FILTER (WHERE is_fraud = TRUE) AS fraud_건수
FROM fraud_transactions
GROUP BY channel
ORDER BY fraud_건수 DESC;
